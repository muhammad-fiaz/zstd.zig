test "decodeSingleStreamLenient tolerates padding" {
    // Lenient mode exists for encoder tests; it must still decode correctly
    // on well-formed input. Weights {2,1,1} tableLog 2 give a 4-cell table;
    // an all-zero stream decodes to symbol 0 repeatedly.
    const weights = [_]u8{ 2, 1, 1 };
    var dec = try buildDecoder(testing.allocator, &weights, 2);
    defer dec.deinit();
    var src = [_]u8{ 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01 };
    var dst: [4]u8 = undefined;
    try decodeSingleStreamLenient(&dst, &src, &dec);
    for (dst) |b| try testing.expect(b < weights.len);
}

