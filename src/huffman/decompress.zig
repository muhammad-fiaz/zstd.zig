test "buildDecoder accepts the format maximum table log" {
    // A depth-12 code is legal even though encoders rarely produce one.
    const weights = [_]u8{ 12, 12 };
    var dec = try buildDecoder(testing.allocator, &weights, 12);
    defer dec.deinit();
    try testing.expectEqual(@as(u8, 12), dec.max_bits);
    try testing.expectEqual(@as(usize, 4096), dec.table.len);
}

test "buildDecoder fills every cell exactly once" {
    // A complete code: weights {1,1,2,2,2} sum(2^(w-1)) = 1+1+2+2+2 = 8.
    // Larger weights mean shorter codes: weight 2 -> 2-bit codes, and the
    // weight-1 symbols get the longest (3-bit) codes.
    const weights = [_]u8{ 1, 1, 2, 2, 2 };
    var dec = try buildDecoder(testing.allocator, &weights, 3);
    defer dec.deinit();
    try testing.expectEqual(@as(usize, 8), dec.table.len);
    var seen_long = false;
    var seen_short = false;
    for (dec.table) |e| {
        try testing.expect(e.symbol < weights.len);
        // No cell may be left at the zero-initialised sentinel.
        try testing.expect(e.nbBits >= 1);
        if (e.nbBits == 3) seen_long = true;
        if (e.nbBits == 2) seen_short = true;
    }
    try testing.expect(seen_long);
    try testing.expect(seen_short);
}

test "buildDecoder symbols populated" {
    const weights = [_]u8{ 2, 1, 1 };
    var dec = try buildDecoder(testing.allocator, &weights, 2);
    defer dec.deinit();
    var found = [_]bool{ false, false, false };
    for (dec.table) |e| {
        if (e.symbol < 3) found[e.symbol] = true;
    }
    try testing.expect(found[0]);
    try testing.expect(found[1]);
    try testing.expect(found[2]);
}

