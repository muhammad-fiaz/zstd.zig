test "readStats direct representation" {
    // header 128 => 1 weight; nibble 1 means weight 1. weightTotal = 1,
    // tableLog = 1, rest = 2 - 1 = 1 -> implied last weight 1, so the code is
    // {1,1}: the two-symbol table a Huffman encoder emits for equal counts.
    var weights: [256]u8 = @splat(0);
    var ranks: [max_table_log + 1]u32 = @splat(0);
    var nbSymbols: usize = 0;
    var tableLog: u8 = 0;
    const src = [_]u8{ 128, 0x10 };
    const used = try readStats(&weights, &ranks, &nbSymbols, &tableLog, &src, testing.allocator);
    try testing.expectEqual(@as(usize, 2), used);
    try testing.expectEqual(@as(usize, 2), nbSymbols);
    try testing.expectEqual(@as(u8, 1), tableLog);
    try testing.expectEqual(@as(u8, 1), weights[0]);
    try testing.expectEqual(@as(u8, 1), weights[1]);
    try testing.expectEqual(@as(u32, 2), ranks[1]);
}

test "readStats rejects a direct table no Huffman tree could produce" {
